/**
 * Потолок загрузки файлов — одно значение на весь фронт.
 *
 * Держится в согласии с `MAX_UPLOAD_TOTAL_BYTES` в бэкенде и с
 * `client_max_body_size` в nginx прода. Раньше лимита на фронте не было вовсе:
 * пользователь выбирал десяток сканов на 61 МБ, ждал выгрузки по мобильному
 * интернету, получал 413 от nginx и надпись «не удалось обработать файл» —
 * без единого намёка, что дело в размере. 11.08 так сгорело три попытки подряд.
 */
export const MAX_UPLOAD_TOTAL_BYTES = 100 * 1024 * 1024;

export const totalSize = (files: File[]): number =>
  files.reduce((sum, f) => sum + f.size, 0);

/**
 * Размер в мегабайтах — ТОЛЬКО число, без единицы измерения. Единица живёт в
 * переводах: интерфейс на семи языках, и «МБ» в коде уехало бы русским текстом
 * в китайскую локаль.
 */
export const sizeInMb = (bytes: number): string =>
  (bytes / 1024 / 1024).toFixed(bytes < 10 * 1024 * 1024 ? 1 : 0);

/**
 * Отказ, у которого есть человеческая причина и понятное действие. Отдельный
 * тип нужен, чтобы обработчик показал текст как есть, а не подменил его общей
 * заглушкой «не удалось обработать файл» — именно эта подмена и оставляла
 * пользователя без объяснения.
 */
export class UploadRejected extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'UploadRejected';
  }
}

/**
 * Часовой пояс устройства в формате IANA («Asia/Yekaterinburg»).
 * Пустая строка, если браузер его не отдаёт — бэкенд тогда просто пропустит
 * блок времени, а не подставит заведомо чужой.
 */
export const clientTimeZone = (): string => {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone || '';
  } catch {
    return '';
  }
};
