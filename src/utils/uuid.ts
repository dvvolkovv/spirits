/**
 * Один общий разбор uuid для всей очереди 1: карточка действия продукта живёт
 * по ссылкам `?action=`, `?pa=`/`#pa=` и в блоке `product-action` из ответа
 * ассистента — четыре места, которые раньше держали одно и то же регулярное
 * выражение каждое само по себе (находка ревью, F2).
 */
export const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(s: unknown): s is string {
  return typeof s === 'string' && UUID_RE.test(s);
}
