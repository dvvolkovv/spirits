import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { RUB_PACKAGES } from '../../config/tokenPackages';

/**
 * Оферта — рукописный документ: LegalModal перечислен в DOCUMENT_BLOCKS
 * скрипта check-no-hardcoded, потому что дробить обязывающий текст на ключи
 * вредно, а переводить его машинно нельзя.
 *
 * Рукописный — значит отстающий: до этой проверки оферта перечисляла три
 * пакета, когда в витрине их стало пять. Тест не пишет текст за человека, но
 * не даёт забыть пакет: каждый объём и каждая цена обязаны встречаться в
 * оферте, в русском и английском написании.
 *
 * Этого мало: «пакет не забыт» и «у пакета верная цена» — разные гарантии.
 * Проверка выше ищет каждое число по отдельности, поэтому переставленные
 * местами цены двух пакетов (объёмы остались на местах) её не красят —
 * проверено вручную. Поэтому второй блок требует пару объём—цена целиком:
 * перечисление в оферте после схлопывания пробелов превращается в стабильную
 * форму «3 000 000 токенов — 4 990 ₽».
 *
 * Таблицу тарифов в PaymentInfoModal этот тест больше не читает: с 07.10.2026
 * она не рукописная, а собирается из RUB_PACKAGES, как витрина, и проверяется
 * рендером на всех языках в PaymentInfoModal.test.tsx.
 */

/**
 * При чтении файлов приводим обе стороны сравнения к обычному пробелу.
 *
 * Защита от неразрывного пробела (U+00A0), который может оказаться в самих
 * документах, — а в документах должен стоять обычный (U+0020). Записано
 * escape-последовательностью, а не самим знаком: корректность не должна
 * держаться на невидимом символе, который теряется при копировании.
 */
const NBSP = /\u00A0/g;
const read = (p: string) => readFileSync(p, 'utf8').replace(NBSP, ' ');

const DOCUMENTS = {
  оферта: read('src/components/onboarding/LegalModal.tsx'),
};

/**
 * Разряды разделяем сами, а не через toLocaleString.
 *
 * Тест сверяет НАПИСАНИЕ числа в рукописном документе, а не результат
 * локализации, и не должен зависеть от ICU-данных сборки Node: при урезанном
 * ICU локаль молча деградирует. Заодно отпадает неразрывный пробел, которым
 * toLocaleString('ru-RU') разделяет разряды, — в документах стоит обычный.
 */
const group = (n: number, sep: string) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, sep);

/** «3 000 000» — как пишут в русском блоке. */
const ru = (n: number) => group(n, ' ');
/** «3,000,000» — как пишут в английском блоке. */
const en = (n: number) => group(n, ',');

describe('цены в рукописных документах', () => {
  for (const [docName, text] of Object.entries(DOCUMENTS)) {
    for (const p of RUB_PACKAGES) {
      it(`${docName}: пакет ${p.id} указан объёмом`, () => {
        expect(text).toContain(ru(p.tokens));
        expect(text).toContain(en(p.tokens));
      });

      it(`${docName}: пакет ${p.id} указан ценой`, () => {
        expect(text).toContain(ru(p.priceRub));
        expect(text).toContain(en(p.priceRub));
      });
    }
  }
});

describe('оферта: объём стоит рядом со своей ценой', () => {
  // Перенос строк JSX режет перечисление между объёмом и ценой, поэтому
  // построчная проверка (как в таблице ниже) тут не годится: схлопываем все
  // пробельные последовательности, включая переводы строк, в один пробел —
  // форма перечисления становится стабильной. Разделитель — длинное тире
  // (U+2014), как в самом файле, а не дефис.
  const offer = DOCUMENTS['оферта'].replace(/\s+/g, ' ');

  for (const p of RUB_PACKAGES) {
    it(`пакет ${p.id} указан парой объём — цена по-русски`, () => {
      expect(offer).toContain(`${ru(p.tokens)} токенов — ${ru(p.priceRub)} ₽`);
    });

    it(`пакет ${p.id} указан парой объём — цена по-английски`, () => {
      expect(offer).toContain(`${en(p.tokens)} tokens — RUB ${en(p.priceRub)}`);
    });
  }
});
