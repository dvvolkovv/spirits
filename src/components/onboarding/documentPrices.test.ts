import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { RUB_PACKAGES } from '../../config/tokenPackages';

/**
 * Оферта и таблица тарифов — рукописные документы: они перечислены в
 * DOCUMENT_BLOCKS скрипта check-no-hardcoded, потому что дробить обязывающий
 * текст на ключи вредно, а переводить его машинно нельзя.
 *
 * Рукописный — значит отстающий: до этой проверки оферта перечисляла три
 * пакета, когда в витрине их стало пять. Тест не пишет текст за человека, но
 * не даёт забыть пакет: каждый объём и каждая цена обязаны встречаться в обоих
 * документах, в русском и английском написании.
 *
 * Этого мало: «пакет не забыт» и «у пакета верная цена» — разные гарантии.
 * Проверка выше ищет каждое число по отдельности, поэтому переставленные
 * местами цены двух пакетов (объёмы остались на местах) её не красят —
 * проверено вручную. Два блока ниже закрывают именно пару объём—цена, каждый
 * своим способом, потому что структура документов разная:
 *
 * - в оферте перечисление после схлопывания пробелов превращается в
 *   стабильную форму «3 000 000 токенов — 4 990 ₽» — её и требуем целиком;
 * - в таблице тарифов каждая строка `<tr>` — это одна строка исходного
 *   файла, объём и цена внутри неё соседствуют — требуем, чтобы такая строка
 *   нашлась.
 *
 * Что по-прежнему не проверено (честно, чтобы не создавать ложного
 * ощущения полноты): пара объём—цена может стоять на месте, но с чужим
 * названием пакета рядом — если некто переставит местами подписи "Бизнес" и
 * "Максимальный" в таблице, оставив их объём и цену как есть, этот тест
 * останется зелёным. Соответствие названия пакета его паре здесь не
 * проверяется.
 */

/**
 * Обе стороны сравнения приводим к обычному пробелу.
 *
 * Иначе тест был бы вечно красным на ровном месте: toLocaleString('ru-RU')
 * разделяет разряды НЕразрывным пробелом (U+00A0), а в документах стоит
 * обычный (U+0020). Записано escape-последовательностью, а не самим знаком:
 * корректность не должна держаться на невидимом символе, который теряется
 * при копировании.
 */
const NBSP = /\u00A0/g;
const read = (p: string) => readFileSync(p, 'utf8').replace(NBSP, ' ');

const DOCUMENTS = {
  оферта: read('src/components/onboarding/LegalModal.tsx'),
  'таблица тарифов': read('src/components/onboarding/PaymentInfoModal.tsx'),
};

/** «3 000 000» — как пишут по-русски и по-французски. */
const ru = (n: number) => n.toLocaleString('ru-RU').replace(NBSP, ' ');
/** «3,000,000» — как пишут по-английски. */
const en = (n: number) => n.toLocaleString('en-US');

describe('цены в рукописных документах', () => {
  for (const [docName, text] of Object.entries(DOCUMENTS)) {
    for (const p of RUB_PACKAGES) {
      it(`${docName}: пакет ${p.id} указан объёмом`, () => {
        expect(text).toContain(ru(p.tokens));
        expect(text).toContain(en(p.tokens));
      });

      it(`${docName}: пакет ${p.id} указан ценой`, () => {
        expect(text).toContain(ru(p.priceRub));
        expect(text).toContain(en(p.priceRub));
      });
    }
  }
});

describe('оферта: объём стоит рядом со своей ценой', () => {
  // Перенос строк JSX режет перечисление между объёмом и ценой, поэтому
  // построчная проверка (как в таблице ниже) тут не годится: схлопываем все
  // пробельные последовательности, включая переводы строк, в один пробел —
  // форма перечисления становится стабильной. Разделитель — длинное тире
  // (U+2014), как в самом файле, а не дефис.
  const offer = DOCUMENTS['оферта'].replace(/\s+/g, ' ');

  for (const p of RUB_PACKAGES) {
    it(`пакет ${p.id} указан парой объём — цена по-русски`, () => {
      expect(offer).toContain(`${ru(p.tokens)} токенов — ${ru(p.priceRub)} ₽`);
    });

    it(`пакет ${p.id} указан парой объём — цена по-английски`, () => {
      expect(offer).toContain(`${en(p.tokens)} tokens — RUB ${en(p.priceRub)}`);
    });
  }
});

describe('таблица тарифов: объём и цена в одной строке файла', () => {
  // Каждая строка <tr> занимает одну строку исходника, объём и цена внутри
  // неё соседствуют через разметку ячеек. Перестановка цен между строками
  // разводит объём и цену по разным строкам файла — проверка это ловит.
  const rows = DOCUMENTS['таблица тарифов'].split('\n');

  for (const p of RUB_PACKAGES) {
    it(`пакет ${p.id} указан парой объём — цена по-русски`, () => {
      const ruTokens = ru(p.tokens);
      const ruPrice = ru(p.priceRub);
      expect(rows.some((line) => line.includes(ruTokens) && line.includes(ruPrice))).toBe(true);
    });

    it(`пакет ${p.id} указан парой объём — цена по-английски`, () => {
      const enTokens = en(p.tokens);
      const enPrice = en(p.priceRub);
      expect(rows.some((line) => line.includes(enTokens) && line.includes(enPrice))).toBe(true);
    });
  }
});
