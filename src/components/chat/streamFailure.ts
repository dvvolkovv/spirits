/**
 * Оборвался транспорт или упал ход: две разные вещи, которые чат до 17.09.2026
 * не различал.
 *
 * Жалоба с прода (мобильный веб): человек отправляет реплику, уходит в другое
 * окно, возвращается — и видит пузырь «Извините, произошла ошибка при обработке
 * вашего сообщения», а прямо под ним нормальный ответ ассистента. Ошибки не
 * было: мобильный браузер усыпляет фоновую вкладку и рвёт живое соединение,
 * `reader.read()` падает сетевой ошибкой (имя НЕ AbortError, поэтому ранний
 * выход из catch её не ловил), и чат честно рапортовал о сбое. Бэкенд при этом
 * ход досчитывает — он специально продолжает читать релей после ухода клиента
 * (chat.service.ts, «client disconnected ... but continuing stream») и пишет
 * ответ в БД, откуда его через несколько секунд поднимает поллинг истории.
 *
 * Отсюда правило: пузырь ошибки показываем, только если ход НЕ идёт на сервере.
 * Во всех остальных случаях молчим и отдаём человека карточке «Ассистент
 * работает» — она уже есть и сделана ровно для этого (ход считается не в этой
 * вкладке, например после F5).
 *
 * Врать «ошибка» дороже, чем промолчать, ещё по одной причине: увидев её,
 * человек шлёт реплику заново — а релей пре-эмптит предыдущий процесс на том же
 * sessionId и этим убивает свой же ход, который вот-вот дописался бы.
 */

export interface StreamFailureContext {
  /**
   * Бэкенд ответил заголовками (`response.ok`) и мы начали читать тело.
   *
   * Ключевой признак: раз запрос дошёл — ход принят и будет досчитан независимо
   * от того, дожили мы до конца стрима или нет.
   */
  responseStarted: boolean;
  /** Из стрима разобралось хоть одно событие (begin/item/ping/end). */
  receivedAnyEvent: boolean;
  /**
   * Что ответил `/webhook/chat/active-turn`: идёт ли ход прямо сейчас.
   * `null` — спросить не удалось (у НАС нет сети; про сервер это не говорит
   * ничего).
   */
  turnActive: boolean | null;
}

/**
 * Показывать ли пузырь «произошла ошибка».
 *
 * Единственный случай, когда «нет» неверно: бэкенд успел отдать заголовки и
 * упасть, не отправив ни одного события, и при этом мы не смогли его
 * переспросить. Тогда человек увидит карточку «Ассистент работает», которая
 * погаснет на следующем опросе. Это дешевле ложной ошибки на живом ходе —
 * лишний пузырь приходил на КАЖДОМ сворачивании окна.
 */
export function shouldShowStreamError(ctx: StreamFailureContext): boolean {
  // Запрос не дошёл (нет сети в момент отправки, 5xx, битый ответ) — на сервере
  // ничего не считается, и ответа ждать неоткуда. Это настоящий сбой.
  if (!ctx.responseStarted) return true;

  // Ход шёл: ответ либо уже в БД, либо допишется туда. Поллинг его поднимет.
  if (ctx.receivedAnyEvent) return false;

  // Событий не было — спрашиваем бэкенд. Явное «хода нет» означает, что он
  // оборвался на старте: вот тут человеку и правда надо сказать про ошибку.
  return ctx.turnActive === false;
}

/**
 * Нужен ли запрос к `/webhook/chat/active-turn` после обрыва.
 *
 * Спрашиваем только в неоднозначном случае: платить лишним round-trip'ом там,
 * где ответ и так известен, незачем — обрыв случается в том числе при потере
 * сети, и запрос будет висеть до таймаута.
 */
export function needsActiveTurnProbe(
  ctx: Pick<StreamFailureContext, 'responseStarted' | 'receivedAnyEvent'>,
): boolean {
  return ctx.responseStarted && !ctx.receivedAnyEvent;
}
