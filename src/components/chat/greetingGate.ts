/**
 * Автоприветствие уходит без человека — значит, только в чат, где он за это
 * время ничего не написал. Решение «чат пуст» принимается по ответу истории,
 * а отправка случается позже: перед ней бывают смена ассистента на сервере и
 * пауза. Если в этом окне человек отправил своё сообщение или положил его в
 * очередь, приветствие пришло бы следом в ту же сессию и прервало его ход —
 * релей переключается на новое сообщение (прод, 08.10.2026).
 */
export interface GreetingCheck {
  /** Реплик в очереди досылки. */
  queuedCount: number;
  /** Человек нажал «отправить», а отправка ещё в пути. */
  sending: boolean;
  /** Сколько было отправок, когда решили приветствовать. */
  sendSeqAtDecision: number;
  /** Сколько отправок сейчас. */
  sendSeqNow: number;
}

export function greetingStillWanted(c: GreetingCheck): boolean {
  return c.queuedCount === 0 && !c.sending && c.sendSeqNow === c.sendSeqAtDecision;
}
