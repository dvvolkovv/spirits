/**
 * «Ход идёт где-то ещё»: ответ ассистента, который считается на сервере, но не
 * стримится в эту вкладку — человек перезагрузил страницу или пишет с другого
 * устройства.
 *
 * Зачем отдельный модуль. Релей (relay-agent/server.mjs) убивает предыдущий
 * процесс `claude` при новом запросе на тот же sessionId. Локальный ход мы
 * видим по isTyping и умеем копить очередь, а удалённый до сих пор не видели
 * совсем: после F5 отправка уходила немедленно и рвала чужой ответ. Ровно этот
 * сценарий описан в ChatInterface у карточки «Ассистент работает»: человек ждёт
 * в тишине, шлёт «?» — и обрывает собственный ход.
 *
 * Почему нельзя было просто дописать remoteTurnActive в turnBusy: этим же
 * признаком гейтится опрос active-turn, который сам его и выставляет. Флаг
 * встал → опрос выключился и обнулил флаг → включился и снова поднял: качели.
 * Поэтому здесь два РАЗНЫХ понятия, и слипаться им нельзя.
 */

export interface TurnState {
  /** Стрим идёт прямо в этой вкладке. */
  isTyping: boolean;
  /** Сколько реплик ждёт досылки. */
  queuedCount: number;
  /** Бэкенд говорит, что ход по этому ассистенту считается прямо сейчас. */
  remoteTurnActive: boolean;
}

/**
 * Гейт поллинга истории: «эта вкладка ещё не закончила свой ход».
 *
 * Удалённый ход сюда НЕ входит: поллинг истории для того и нужен, чтобы
 * подобрать чужой ответ, когда он допишется в БД.
 */
export function localTurnBusy(s: Pick<TurnState, 'isTyping' | 'queuedCount'>): boolean {
  return s.isTyping || s.queuedCount > 0;
}

/**
 * Решение «слать или копить». Здесь удалённый ход учитывается: отправить в него
 * — значит убить чужой ответ на полуслове.
 */
export function turnRunningAnywhere(s: TurnState): boolean {
  return localTurnBusy(s) || s.remoteTurnActive;
}

/** Насколько свежим считаем ответ опроса active-turn. Интервал опроса — 5с. */
export const REMOTE_KNOWLEDGE_FRESH_MS = 6000;

/**
 * Нужно ли спросить бэкенд синхронно перед отправкой.
 *
 * Опрос идёт раз в 5 секунд, и сразу после F5 первый ответ ещё не пришёл — в
 * этом окне мы про удалённый ход не знаем ничего. Если знание свежее и говорит
 * «тихо» — верим ему и не платим лишним запросом на каждую отправку.
 */
export function needsFreshRemoteCheck(
  lastCheckAtMs: number | null,
  nowMs: number,
  freshMs: number = REMOTE_KNOWLEDGE_FRESH_MS,
): boolean {
  if (lastCheckAtMs === null) return true;
  return nowMs - lastCheckAtMs >= freshMs;
}

/** После скольких минут залипшего флага предлагаем человеку обойти блокировку. */
export const REMOTE_STUCK_MS = 2 * 60 * 1000;

/**
 * Показывать ли кнопку «отправить всё равно».
 *
 * Флаг приходит с бэкенда. Если реестр живых стримов там протечёт, флаг
 * залипнет — и человек окажется заперт: всё, что он пишет, копится и не уходит.
 * Автоматически снимать блокировку по таймеру НЕЛЬЗЯ: ходы юридических
 * ассистентов доходят до двадцати минут, и автоснятие рвало бы как раз самые
 * дорогие из них. Поэтому решение отдаём человеку — но только после того, как
 * ожидание стало непохожим на обычное.
 */
export function shouldOfferOverride(
  remoteTurnActive: boolean,
  activeSinceMs: number | null,
  nowMs: number,
  stuckMs: number = REMOTE_STUCK_MS,
): boolean {
  if (!remoteTurnActive || activeSinceMs === null) return false;
  return nowMs - activeSinceMs >= stuckMs;
}
