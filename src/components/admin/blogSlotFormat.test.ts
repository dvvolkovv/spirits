import { afterEach, describe, it, expect } from 'vitest';
import { formatSlotAt, formatSlotWhen } from './blogSlotFormat';

/**
 * Ожидаемые строки сверены не с кодом, а с независимым оракулом —
 * `Intl.DateTimeFormat('ru-RU', { timeZone: 'Europe/Moscow' })`: он считает
 * московское время через базу поясов, а не через сдвиг на три часа, как
 * форматтер. Первый блок — те же входы и выходы, что в бэковом
 * `blog-slot-format.spec.ts`: фраза в админке обязана совпадать с той, что
 * владелец видит в Telegram.
 */
const at = (iso: string) => new Date(iso);

describe('та же фраза, что в Telegram (входы бэкового спека)', () => {
  const cases: [slot: string, now: string, phrase: string][] = [
    ['2026-09-24T07:00:00Z', '2026-09-21T05:00:00Z', 'в четверг, 24 сентября, в 10:00 МСК'],
    ['2026-09-21T07:00:00Z', '2026-09-21T05:00:00Z', 'сегодня в 10:00 МСК'],
    ['2026-09-23T07:00:00Z', '2026-09-22T12:00:00Z', 'завтра в 10:00 МСК'],
    ['2026-09-22T07:00:00Z', '2026-09-21T22:00:00Z', 'сегодня в 10:00 МСК'],
    ['2027-01-01T05:00:00Z', '2026-12-31T15:00:00Z', 'завтра в 08:00 МСК'],
    ['2026-09-29T07:00:00Z', '2026-09-21T05:00:00Z', 'во вторник, 29 сентября, в 10:00 МСК'],
    ['2026-09-27T07:00:00Z', '2026-09-21T05:00:00Z', 'в воскресенье, 27 сентября, в 10:00 МСК'],
    ['2026-12-31T21:00:00Z', '2026-09-21T05:00:00Z', 'в пятницу, 1 января, в 00:00 МСК'],
    ['2026-09-24T04:05:00Z', '2026-09-21T05:00:00Z', 'в четверг, 24 сентября, в 07:05 МСК'],
  ];

  it.each(cases)('%s при now=%s → «%s»', (slot, now, phrase) => {
    expect(formatSlotWhen(at(slot), at(now))).toBe(phrase);
  });
});

describe('падежи и предлог', () => {
  // now — понедельник 21.09, так что ни один из слотов не «сегодня/завтра».
  const now = at('2026-09-21T05:00:00Z');

  it('день недели в винительном, перед вторником — «во»', () => {
    expect(formatSlotWhen(at('2026-09-28T07:00:00Z'), now)).toBe('в понедельник, 28 сентября, в 10:00 МСК');
    expect(formatSlotWhen(at('2026-09-29T07:00:00Z'), now)).toBe('во вторник, 29 сентября, в 10:00 МСК');
    expect(formatSlotWhen(at('2026-09-30T07:00:00Z'), now)).toBe('в среду, 30 сентября, в 10:00 МСК');
    expect(formatSlotWhen(at('2026-10-01T07:00:00Z'), now)).toBe('в четверг, 1 октября, в 10:00 МСК');
    expect(formatSlotWhen(at('2026-10-02T07:00:00Z'), now)).toBe('в пятницу, 2 октября, в 10:00 МСК');
    expect(formatSlotWhen(at('2026-10-03T07:00:00Z'), now)).toBe('в субботу, 3 октября, в 10:00 МСК');
    expect(formatSlotWhen(at('2026-10-04T07:00:00Z'), now)).toBe('в воскресенье, 4 октября, в 10:00 МСК');
  });

  it('месяц в родительном: «1 марта», а не «1 март»', () => {
    const months = [
      'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
      'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
    ];
    months.forEach((month, i) => {
      const slot = new Date(Date.UTC(2027, i, 1, 7, 0)); // 1-е число, 10:00 МСК
      expect(formatSlotWhen(slot, now)).toContain(`, 1 ${month}, в 10:00 МСК`);
    });
  });
});

/**
 * «Сегодня/завтра» — по московским суткам. Московская и UTC-дата расходятся
 * с 00:00 до 03:00 МСК (21:00–24:00 UTC): проверка только «вечером после
 * 21:00 МСК» подмену на UTC не поймала бы — там обе даты ещё совпадают.
 * Поэтому здесь оба окна.
 */
describe('«сегодня/завтра» по Москве', () => {
  it('23:30 МСК — ещё те же сутки: утренний слот наступающего дня «завтра»', () => {
    const now = at('2026-09-21T20:30:00Z'); // пн 21.09, 23:30 МСК
    expect(formatSlotWhen(at('2026-09-22T07:00:00Z'), now)).toBe('завтра в 10:00 МСК');
  });

  it('00:30 МСК (21:30 UTC) — в Москве уже новые сутки: слот этого утра «сегодня»', () => {
    const now = at('2026-09-21T21:30:00Z'); // по UTC ещё 21.09, в Москве вт 22.09, 00:30
    expect(formatSlotWhen(at('2026-09-22T07:00:00Z'), now)).toBe('сегодня в 10:00 МСК');
  });

  it('00:30 МСК — «завтра» отсчитывается от московских суток, а не от UTC', () => {
    const now = at('2026-09-21T21:30:00Z'); // вт 22.09, 00:30 МСК
    expect(formatSlotWhen(at('2026-09-23T07:00:00Z'), now)).toBe('завтра в 10:00 МСК');
  });

  it('слот в 00:30 МСК — это уже следующие московские сутки, хотя по UTC дата та же', () => {
    const now = at('2026-09-22T12:00:00Z'); // вт 22.09, 15:00 МСК
    expect(formatSlotWhen(at('2026-09-22T21:30:00Z'), now)).toBe('завтра в 00:30 МСК');
  });
});

/**
 * Админку открывают откуда угодно, а слот задан по Москве. На маке пояс
 * московский, и форматтер на `getDate()` прошёл бы все тесты выше — поэтому
 * тот же расчёт гоняем в чужих поясах. Сначала убеждаемся, что пояс
 * действительно переключился: иначе тест зеленел бы впустую.
 */
describe('пояс браузера не влияет', () => {
  const original = process.env.TZ;
  afterEach(() => {
    if (original === undefined) delete process.env.TZ;
    else process.env.TZ = original;
  });

  it.each([
    ['UTC', 0],
    ['America/New_York', 240],
    ['Asia/Tokyo', -540],
  ])('в поясе %s фраза та же', (zone, offset) => {
    process.env.TZ = zone;
    expect(at('2026-09-21T21:30:00Z').getTimezoneOffset()).toBe(offset);

    const now = at('2026-09-21T21:30:00Z'); // вт 22.09, 00:30 МСК
    expect(formatSlotWhen(at('2026-09-22T07:00:00Z'), now)).toBe('сегодня в 10:00 МСК');
    expect(formatSlotWhen(at('2026-09-23T07:00:00Z'), now)).toBe('завтра в 10:00 МСК');
    expect(formatSlotWhen(at('2026-09-29T07:00:00Z'), now)).toBe('во вторник, 29 сентября, в 10:00 МСК');
  });
});

describe('formatSlotAt', () => {
  const now = at('2026-09-21T05:00:00Z');

  it('разбирает ISO из API', () => {
    expect(formatSlotAt('2026-09-24T07:00:00.000Z', now)).toBe('в четверг, 24 сентября, в 10:00 МСК');
  });

  it('неразборчивую строку отдаёт как есть, а не «в undefined, NaN»', () => {
    expect(formatSlotAt('не дата', now)).toBe('не дата');
  });
});
