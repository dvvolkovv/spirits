import { describe, it, expect } from 'vitest';
import { formatDuration } from './callsFormat';

/**
 * В таблице звонков стоят суммы за месяц, поэтому длительность показывается
 * словами, а не в секундах. Ветки тут ровно те, на которых легко ошибиться:
 * час без остатка, короткий звонок и пустое значение.
 */
describe('formatDuration', () => {
  it('часы показывает вместе с минутами', () => {
    expect(formatDuration(7830)).toBe('2 ч 10 мин');
  });

  it('ровный час не теряет ноль минут', () => {
    // Раньше тут был соблазн писать `${h} ч` при m === 0 — тогда «2 ч 0 мин»
    // и «2 ч 59 мин» выглядели бы одинаково при округлении вниз.
    expect(formatDuration(3600)).toBe('1 ч 0 мин');
  });

  it('меньше часа — только минуты', () => {
    expect(formatDuration(930)).toBe('15 мин');
  });

  it('короткий звонок не схлопывается в ноль минут', () => {
    // 40-секундный звонок — это «сорвался», и в таблице он должен читаться
    // именно так, а не как «0 мин», неотличимое от отсутствия разговора.
    expect(formatDuration(40)).toBe('40 с');
  });

  it('нулевая длительность — прочерк, а не «0 с»', () => {
    expect(formatDuration(0)).toBe('—');
  });
});
