/**
 * Аренда продукта в кабинете: то, что считается одинаково в списке и в чате.
 *
 * Отдельный модуль, а не пара функций внутри ProductsListView: этим же
 * пользуется ProductChat (ссылка на пополнение), а второй экземпляр адреса
 * или порога разъехался бы с первым молча.
 */
/**
 * Месячная аренда продукта в токенах.
 *
 * Зеркало `RENT_TOKENS` из spirits_back/src/products/rent.service.ts. Своё
 * число здесь не от лени: сервер эту величину наружу не отдаёт ни одним полем,
 * а без неё нельзя ответить на единственный вопрос владельца спящего продукта
 * — «сколько положить», и нельзя предсказать, разбудит ли сервер продукт сам.
 * Разъедется с бэкендом молча, поэтому и ссылка на первоисточник.
 *
 * Живёт в этом модуле, а не в productsApi: тесты кабинета подменяют весь
 * productsApi заглушкой, и константа, вынесенная туда, приезжала бы в них
 * `undefined` — все сравнения с балансом молча стали бы ложными, а батарея
 * осталась бы зелёной.
 */
export const RENT_TOKENS = 50_000;

/**
 * Куда вести пополнять. Тот же адрес, что у остальных витрин токенов
 * (ProfileView, VideoCreateForm): `?view=tokens` открывает модал покупки на
 * /chat — см. ChatPage.
 */
export const TOPUP_HREF = '/chat?view=tokens';

/**
 * Куда вести владельца ПОГАШЕННОГО продукта.
 *
 * Блокировку снимает только администратор, то есть единственное доступное
 * владельцу действие — написать людям. `/support` — не выдуманный адрес: это
 * живой раздел заявок (SupportView, маршрут в App.tsx), тот же, куда уводит
 * «Помощь». Без ссылки текст «напишите нам» назвал бы действие, места для
 * которого на экране нет, — ровно та ошибка, за которую в этой работе уже
 * переписывали отказ про предел аккаунта.
 *
 * Рядом с TOPUP_HREF, а не в компоненте: адрес нужен и списку, и чату правок,
 * и второй его экземпляр разъехался бы с первым молча.
 */
export const SUPPORT_HREF = '/support';

/**
 * За сколько до списания предупреждать.
 *
 * Трое суток, потому что сборщик аренды ходит раз в сутки: списание случится
 * в пределах суток ПОСЛЕ `paid_until`, и предупреждение «завтра» оставило бы
 * владельцу меньше времени, чем кажется. Больше трёх — тревога, на которую
 * ещё нечего отвечать.
 */
export const RENT_SOON_MS = 3 * 24 * 60 * 60 * 1000;

/**
 * Дата списания как ДАТА, а не «осталось N дней».
 *
 * Вкладка кабинета висит открытой сутками: «осталось 2 дня» протухает молча и
 * начинает врать, дата — нет. Срок считает сервер, здесь он только
 * показывается.
 *
 * `null` — срока нет или он нечитаем. Пустое поле бывает у бэкенда,
 * выкаченного до аренды; нечитаемое значение — у ответа SPA-фолбэка, который
 * на этом хостинге умеет отдать 200 с чем угодно. Оба случая обязаны дать
 * молчание, а не строку «Invalid Date» в карточке.
 */
export function formatPaidUntil(iso: string | null | undefined, lang: string): string | null {
  if (!iso) return null;
  const at = new Date(iso);
  if (Number.isNaN(at.getTime())) return null;
  const p = (n: number) => String(n).padStart(2, '0');
  const fallback = `${p(at.getDate())}.${p(at.getMonth() + 1)}.${at.getFullYear()}`;
  try {
    return new Intl.DateTimeFormat(lang, {
      day: '2-digit',
      month: '2-digit',
      year: 'numeric',
    }).format(at);
  } catch {
    // Незнакомый язык или сборка node без локальных данных — формат
    // выбранного языка потерян, но дата важнее формата.
    return fallback;
  }
}

/** Месячная аренда числом для текста карточки. */
export function formatRentAmount(lang: string): string {
  try {
    return new Intl.NumberFormat(lang).format(RENT_TOKENS);
  } catch {
    return String(RENT_TOKENS);
  }
}

/**
 * Пора ли предупреждать о списании.
 *
 * ОБА УСЛОВИЯ СРАЗУ, и это главное в этой функции: срок близко И на балансе
 * не хватает на следующий месяц. Тревога без причины приучает её не замечать,
 * а тревожить владельца с полным балансом не о чем — с него просто спишут.
 *
 * Баланс `undefined` — «не знаем» (профиль ещё не доехал), и это НЕ повод для
 * тревоги: кабинет уже один раз учился не пугать там, где сам ничего не знает
 * (вердикт про сервер продуктов).
 */
export function rentWarningDue(
  paidUntil: string | null | undefined,
  balance: number | undefined,
  now: number = Date.now(),
): boolean {
  if (typeof balance !== 'number') return false;
  if (balance >= RENT_TOKENS) return false;
  if (!paidUntil) return false;
  const at = new Date(paidUntil).getTime();
  if (Number.isNaN(at)) return false;
  // Просроченный срок тоже «скоро»: сборщик ходит раз в сутки, и продукт
  // между `paid_until` и оборотом ещё работает — предупреждение там уместнее
  // всего.
  return at - now <= RENT_SOON_MS;
}

/**
 * Хватает ли баланса на месяц аренды — то есть разбудит ли сервер продукт сам.
 *
 * Ровно та арифметика, по которой `wakeAffordable` на бэкенде считает места
 * для пробуждения (баланс / RENT_TOKENS >= 1). Неизвестный баланс — «нет»:
 * обещать пробуждение, ничего не зная о деньгах, нельзя.
 */
export function wakeExpected(balance: number | undefined): boolean {
  return typeof balance === 'number' && balance >= RENT_TOKENS;
}
